// lib/navigation/controllers/trip_recorder.dart

import 'package:latlong2/latlong.dart';

/// Tracks distance driven and records a simplified tracklog while a guided
/// navigation session or free-mode session is active.
///
/// The caller decides *when* to feed positions in (e.g. only while a trip
/// is actually running) — this class just does the bookkeeping.
class TripRecorder {
  TripRecorder({this.tracklogMinDistanceM = 8.0});

  final double tracklogMinDistanceM;

  double _drivenMeters = 0.0;
  LatLng? _lastRecordedPosition;
  LatLng? _lastTracklogLatLng;
  final List<List<double>> _tracklog = [];

  double get drivenMeters => _drivenMeters;
  List<List<double>> get tracklog => List.unmodifiable(_tracklog);

  /// Records a real GPS fix. Jumps of 150m or more are ignored (treated as
  /// GPS glitches) and don't add to the driven distance.
  void recordPosition(LatLng position) {
    if (_lastRecordedPosition != null) {
      final distance = const Distance().as(
        LengthUnit.Meter,
        _lastRecordedPosition!,
        position,
      );
      if (distance > 0 && distance < 150) {
        _drivenMeters += distance;
      }
    }
    _lastRecordedPosition = position;
    _maybeAddTracklogPoint(position);
  }

  /// Records a simulated debug-D-pad step. Distance is always accumulated
  /// since the movement is generated by the app itself (no glitch risk).
  void recordSimulatedStep(LatLng from, LatLng to) {
    _drivenMeters += const Distance()(from, to);
    _lastRecordedPosition = to;
    _maybeAddTracklogPoint(to);
  }

  void _maybeAddTracklogPoint(LatLng position) {
    final last = _lastTracklogLatLng;
    if (last == null ||
        const Distance().as(LengthUnit.Meter, last, position) >=
            tracklogMinDistanceM) {
      _tracklog.add([position.latitude, position.longitude]);
      _lastTracklogLatLng = position;
    }
  }

  void reset() {
    _drivenMeters = 0.0;
    _lastRecordedPosition = null;
    _lastTracklogLatLng = null;
    _tracklog.clear();
  }
}
